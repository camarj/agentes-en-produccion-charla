-- Esquema base de charla en PostgreSQL (Cloud SQL). Equivale a las migraciones
-- SQLite 001–009 (ver el historial de git); se aplica sobre una base nueva, sin
-- migrar datos. Las fechas siguen como texto UTC «AAAA-MM-DD HH:MM:SS», el
-- mismo formato de `datetime('now')`, para que el panel y `isoDeSqlite` no cambien.

CREATE FUNCTION ahora_utc() RETURNS text
  LANGUAGE sql STABLE
  AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE asistentes (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  rol TEXT,
  descripcion TEXT,               -- qué construye o quiere construir con IA
  origen TEXT NOT NULL CHECK (origen IN ('inscrito','invitado')),
  creado_en TEXT NOT NULL DEFAULT ahora_utc()
);

-- Una sola sesión activa por asistente (DevFest 2026-12-05): al entrar de nuevo
-- se revocan las anteriores (`revocada_en`). `orden` reemplaza al rowid de
-- SQLite: la sesión más reciente del asistente es la de mayor `orden`.
CREATE TABLE sesiones (
  token TEXT PRIMARY KEY,
  orden BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
  asistente_id TEXT NOT NULL REFERENCES asistentes(id) ON DELETE CASCADE,
  thread_id TEXT NOT NULL,
  mensajes INTEGER NOT NULL DEFAULT 0,
  creado_en TEXT NOT NULL DEFAULT ahora_utc(),
  revocada_en TEXT
);
CREATE INDEX idx_sesiones_asistente ON sesiones (asistente_id);

CREATE TABLE escalamientos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asistente_id TEXT NOT NULL REFERENCES asistentes(id) ON DELETE CASCADE,
  pregunta TEXT NOT NULL,
  motivo TEXT NOT NULL CHECK (motivo IN ('experiencia_personal','comercial','fuera_de_charla','desacuerdo','falla_tecnica')),
  trace_id TEXT,
  estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','respondida','descartada')),
  creado_en TEXT NOT NULL DEFAULT ahora_utc()
);
CREATE INDEX idx_escalamientos_asistente ON escalamientos (asistente_id);

CREATE TABLE interruptores (
  clave TEXT PRIMARY KEY,
  valor TEXT NOT NULL,
  actualizado_en TEXT NOT NULL DEFAULT ahora_utc()
);
CREATE TABLE eventos_interruptor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave TEXT NOT NULL,
  valor TEXT NOT NULL,
  creado_en TEXT NOT NULL DEFAULT ahora_utc()
);

-- Láminas de la presentación. La búsqueda de texto completo en Postgres llega
-- con T2 (S3); mientras tanto `buscar` arma el tsvector al vuelo (son ~40 filas).
CREATE TABLE laminas (
  numero INTEGER PRIMARY KEY,
  titulo TEXT NOT NULL,
  contenido TEXT NOT NULL,
  notas TEXT
);

-- Votos 👍/👎 de los asistentes sobre las respuestas del agente. Un voto por
-- asistente y traza; votar de nuevo reemplaza el valor.
CREATE TABLE feedback (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asistente_id TEXT NOT NULL REFERENCES asistentes(id) ON DELETE CASCADE,
  trace_id TEXT NOT NULL,
  valor INTEGER NOT NULL CHECK (valor IN (1, -1)),
  creado_en TEXT NOT NULL DEFAULT ahora_utc(),
  UNIQUE (asistente_id, trace_id)
);
CREATE INDEX feedback_trace_id ON feedback (trace_id);

-- Coste estimado acumulado de todos los turnos del agente (USD). Una sola fila.
CREATE TABLE presupuesto (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  coste_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
  actualizado_en TEXT NOT NULL DEFAULT ahora_utc()
);

-- «Jev · la sala en vivo»: un análisis por turno, identificado por su traceId.
-- Solo un extracto corto y redactado de la pregunta: sin asistente, email ni nombre.
CREATE TABLE jev_analisis (
  trace_id TEXT PRIMARY KEY,
  turno_en TEXT NOT NULL,              -- ISO 8601 del inicio del turno
  analizado_en TEXT NOT NULL DEFAULT ahora_utc(),
  pregunta TEXT NOT NULL,              -- extracto redactado
  tema TEXT NOT NULL,
  tema_confianza DOUBLE PRECISION NOT NULL,
  intencion TEXT NOT NULL,
  intencion_confianza DOUBLE PRECISION NOT NULL,
  confusion DOUBLE PRECISION NOT NULL, -- 0 entiende y profundiza · 1 perdido
  confusion_confianza DOUBLE PRECISION NOT NULL,
  valor DOUBLE PRECISION NOT NULL,     -- 0–1 para la sesión de preguntas
  valor_confianza DOUBLE PRECISION NOT NULL,
  respaldada DOUBLE PRECISION,         -- probabilidad; NULL si no se preguntó
  motivo_bloqueo TEXT,
  herramienta_caida INTEGER NOT NULL DEFAULT 0,
  respaldo INTEGER NOT NULL DEFAULT 0,
  sin_modelo INTEGER NOT NULL DEFAULT 0,
  falla INTEGER NOT NULL DEFAULT 0,
  latencia_ms INTEGER NOT NULL,
  tokens_entrada INTEGER,
  modelo TEXT NOT NULL
);
CREATE INDEX jev_analisis_turno_en ON jev_analisis (turno_en);

-- Un turno de chat terminado (PRD §15 G7). Solo datos técnicos. Tiempos en ms epoch.
CREATE TABLE turnos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iniciado_ms BIGINT NOT NULL,
  duracion_ms BIGINT,                 -- null: el turno no terminó con respuesta
  resultado TEXT NOT NULL CHECK (resultado IN ('ok','bloqueo','falla')),
  tipo_falla TEXT CHECK (tipo_falla IN ('tiempo','herramienta','modelo','otro')),
  motivo_bloqueo TEXT,
  modelo TEXT,                        -- modelo que respondió (null si ninguno)
  respaldo INTEGER NOT NULL DEFAULT 0 CHECK (respaldo IN (0,1)),
  trace_id TEXT
);
CREATE INDEX idx_turnos_iniciado ON turnos (iniciado_ms);

-- Eventos de salud del panel (PRD §15 G7). Los repetidos del mismo tipo en un
-- minuto se agrupan (`cantidad`). Solo datos técnicos.
CREATE TABLE eventos_salud (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo TEXT NOT NULL,
  servicio TEXT NOT NULL,
  nivel TEXT NOT NULL CHECK (nivel IN ('ok','aviso','falla')),
  cantidad INTEGER NOT NULL DEFAULT 1,
  primero_ms BIGINT NOT NULL,
  ultimo_ms BIGINT NOT NULL,
  trace_id TEXT
);
CREATE INDEX idx_eventos_salud_ultimo ON eventos_salud (ultimo_ms);
CREATE INDEX idx_eventos_salud_tipo ON eventos_salud (tipo, primero_ms);

